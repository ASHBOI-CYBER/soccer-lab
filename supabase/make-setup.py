#!/usr/bin/env python3
"""Join every database file into ONE file to paste into a new Supabase project's SQL editor.

    python make-setup.py        ->  writes setup-new-project.sql next to this script

The order matters and is not quite the order of the file names (waitlist must come before waitlist-codes), so it is
written out here. Add a new file to ORDER, before the finish file, when one is added to this folder.
"""
import os

ORDER = [
    "2026-10-25-base.sql",
    "2026-10-27-multi-teams.sql",
    "2026-10-27-team-streak.sql",
    "2026-10-28-matchday-pack.sql",
    "2026-10-28-numeric-team-codes.sql",
    "2026-10-29-backups.sql",
    "2026-10-29-gift-trials.sql",
    "2026-10-30-lifetime-codes.sql",
    "2026-10-30-safety.sql",
    "2026-11-01-waitlist.sql",
    "2026-11-01-waitlist-codes.sql",
    "2026-11-08-local-teams.sql",
    "2026-11-08-map-teams.sql",
    "2026-11-08-session-media.sql",
    "2026-11-12-creators.sql",
    "2026-11-13-new-project-finish.sql",
]

here = os.path.dirname(os.path.abspath(__file__))
dated = sorted(f for f in os.listdir(here) if f[:4].isdigit() and f.endswith(".sql"))
missing = [f for f in dated if f not in ORDER]
if missing:
    raise SystemExit("Not in ORDER yet: " + ", ".join(missing))

out = [
    "-- SOCCER LAB: the whole database for a NEW, EMPTY Supabase project, in one file.\n"
    "-- Made by make-setup.py from the dated files in this folder. Do not edit this file; edit those and run it again.\n"
    "-- How: Supabase dashboard > SQL Editor > New query > paste all of this > Run. Run it ONCE.\n"
    "-- It runs as one transaction: if anything fails, nothing is kept and it can be run again after the fix.\n\n"
    "begin;\n"
]
for name in ORDER:
    with open(os.path.join(here, name), encoding="utf-8") as f:
        body = f.read().rstrip() + "\n"
    out.append(f"\n-- {'=' * 100}\n-- FILE: {name}\n-- {'=' * 100}\n\n{body}")
out.append("\ncommit;\n")

path = os.path.join(here, "setup-new-project.sql")
with open(path, "w", encoding="utf-8", newline="\n") as f:
    f.write("".join(out))
print(f"wrote {path} ({len(ORDER)} files, {sum(len(x) for x in out):,} characters)")
